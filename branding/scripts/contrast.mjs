// WCAG 2.2 contrast validation for the colour tokens. Writes branding/qa/contrast-report.md
// and exits non-zero if any REQUIRED pair misses its target.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens/colors.json"), "utf8"));

function parse(c) {
  const m = c.match(/rgba?\(([^)]+)\)/);
  if (m) {
    const [r, g, b, a = "1"] = m[1].split(",").map((x) => x.trim());
    return { r: +r, g: +g, b: +b, a: +a };
  }
  const h = c.replace("#", "");
  return {
    r: parseInt(h.slice(0, 2), 16),
    g: parseInt(h.slice(2, 4), 16),
    b: parseInt(h.slice(4, 6), 16),
    a: 1,
  };
}
/** Alpha-composite fg over an opaque bg. */
function over(fg, bg) {
  const f = parse(fg);
  const b = parse(bg);
  const mix = (x, y) => Math.round(x * f.a + y * (1 - f.a));
  return `#${[mix(f.r, b.r), mix(f.g, b.g), mix(f.b, b.b)].map((v) => v.toString(16).padStart(2, "0")).join("")}`;
}
function lum(c) {
  const { r, g, b } = parse(c);
  const ch = (v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b);
}
export function ratio(a, b) {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

// Only validate when run directly (pages.mjs imports `ratio`).
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();

function main() {
  const rows = [];
  const check = (theme, fgName, fg, bgName, bg, target, kind, required = true, note = "") => {
    const r = ratio(fg, bg);
    rows.push({ theme, fgName, bgName, r, target, kind, ok: r >= target, required, note });
  };

  for (const theme of ["dark", "light"]) {
    const t = Object.fromEntries(Object.entries(tokens.theme[theme]).map(([k, v]) => [k, v.$value]));
    const surfaces = ["canvas", "surface", "surface-raised", "surface-overlay"];
    for (const s of surfaces) {
      check(theme, "text", t.text, s, t[s], 4.5, "text");
      check(theme, "text-secondary", t["text-secondary"], s, t[s], 4.5, "text");
      check(theme, "text-muted", t["text-muted"], s, t[s], 4.5, "text");
    }
    check(theme, "accent (link text)", t.accent, "canvas", t.canvas, 4.5, "text");
    check(theme, "accent (link text)", t.accent, "surface", t.surface, 4.5, "text");
    check(theme, "on-accent", t["on-accent"], "accent", t.accent, 4.5, "text");
    check(theme, "on-accent", t["on-accent"], "accent-hover", t["accent-hover"], 4.5, "text");
    check(theme, "text", t.text, "accent-subtle", over(t["accent-subtle"], t.surface), 4.5, "text");
    for (const s of ["success", "warning", "danger", "info"]) {
      check(theme, s, t[s], "surface", t.surface, 4.5, "text");
      check(theme, s, t[s], `${s}-subtle`, over(t[`${s}-subtle`], t.surface), 4.5, "text");
    }
    check(theme, "border-input (form control edge)", t["border-input"], "surface", t.surface, 3, "non-text");
    check(theme, "border-input (form control edge)", t["border-input"], "canvas", t.canvas, 3, "non-text");
    check(theme, "focus-ring", t["focus-ring"], "canvas", t.canvas, 3, "non-text");
    check(theme, "focus-ring", t["focus-ring"], "surface", t.surface, 3, "non-text");
    check(theme, "accent (fill as UI)", t.accent, "surface", t.surface, 3, "non-text");
    for (const [k, v] of Object.entries(tokens.status)) {
      if (k.startsWith("$")) continue;
      check(
        theme,
        `status.${k} icon`,
        v.$value,
        "surface",
        t.surface,
        3,
        "non-text",
        false,
        "Always paired with a text label and distinct icon shape, so colour is not the sole carrier of meaning (WCAG 1.4.1, 1.4.11).",
      );
    }
  }

  const required = rows.filter((r) => r.required);
  const failures = required.filter((r) => !r.ok);
  const fmt = (r) =>
    `| ${r.theme} | ${r.fgName} | ${r.bgName} | ${r.r.toFixed(2)}:1 | ${r.target}:1 ${r.kind} | ${r.ok ? "✅ pass" : r.required ? "❌ FAIL" : "⚠️ exception"} |`;
  const md = [
    "# Contrast report",
    "",
    `_Generated by \`pnpm --filter @webaudit/branding contrast\` from \`tokens/colors.json\`. Targets: WCAG 2.2 AA — 4.5:1 text, 3:1 meaningful non-text UI. Translucent "subtle" backgrounds are alpha-composited over \`surface\` before measuring._`,
    "",
    `**Required pairs:** ${required.length - failures.length}/${required.length} pass.`,
    "",
    "## Required",
    "",
    "| Theme | Foreground | Background | Ratio | Target | Result |",
    "|---|---|---|---|---|---|",
    ...required.map(fmt),
    "",
    "## Documented exceptions (not sole carriers of meaning)",
    "",
    "| Theme | Foreground | Background | Ratio | Target | Result |",
    "|---|---|---|---|---|---|",
    ...rows.filter((r) => !r.required).map(fmt),
    "",
    ...[...new Set(rows.filter((r) => !r.required && !r.ok).map((r) => r.note))].map((n) => `- ${n}`),
    "",
  ];
  mkdirSync(join(root, "qa"), { recursive: true });
  writeFileSync(join(root, "qa/contrast-report.md"), md.join("\n"));
  console.log(`Required contrast pairs: ${required.length - failures.length}/${required.length} pass`);
  for (const f of failures)
    console.log(`  FAIL ${f.theme} ${f.fgName} on ${f.bgName}: ${f.r.toFixed(2)} < ${f.target}`);
  process.exit(failures.length ? 1 : 0);
}
