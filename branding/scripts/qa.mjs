// Asset QA: SVG well-formedness (Chromium DOMParser), PNG dimensions/alpha from the IHDR
// chunk, and local link integrity in previews and docs. Writes qa/asset-validation.md.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const walk = (d) =>
  readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(join(root, "assets")).concat(walk(join(root, "previews")));
const problems = [];

// --- SVG
const svgs = files.filter((f) => f.endsWith(".svg"));
const browser = await chromium.launch();
const page = await browser.newPage();
const results = await page.evaluate(
  (list) =>
    list.map(([name, text]) => {
      const doc = new DOMParser().parseFromString(text, "image/svg+xml");
      const err = doc.querySelector("parsererror");
      const svg = doc.documentElement;
      return {
        name,
        ok: !err && svg.nodeName === "svg",
        viewBox: svg.getAttribute("viewBox"),
        titled: !!svg.querySelector("title"),
      };
    }),
  svgs.map((f) => [relative(root, f), readFileSync(f, "utf8")]),
);
await browser.close();
for (const r of results) {
  if (!r.ok) problems.push(`SVG does not parse: ${r.name}`);
  if (!r.viewBox) problems.push(`SVG missing viewBox: ${r.name}`);
  if (!r.titled && !r.name.includes("/test/")) problems.push(`SVG missing <title>: ${r.name}`);
}

// --- PNG
const EXPECT = {
  "github/social-preview.png": [1280, 640],
  "social/linkedin-launch.png": [1200, 627],
  "social/square-announcement.png": [1080, 1080],
  "social/vertical-announcement.png": [1080, 1350],
  "social/og-default.png": [1200, 630],
  "favicons/apple-touch-icon.png": [180, 180],
  "favicons/icon-192.png": [192, 192],
  "favicons/icon-512.png": [512, 512],
  "favicons/favicon-16.png": [16, 16],
  "favicons/favicon-32.png": [32, 32],
  "github/avatar-500.png": [500, 500],
};
const ALPHA_REQUIRED = [
  "favicons/icon-192.png",
  "favicons/icon-512.png",
  "favicons/favicon-16.png",
  "favicons/favicon-32.png",
  "icons/app-icon-1024.png",
];
const pngs = files.filter((f) => f.endsWith(".png"));
const pngRows = [];
for (const f of pngs) {
  const b = readFileSync(f);
  if (b.readUInt32BE(0) !== 0x89504e47) {
    problems.push(`Not a PNG: ${relative(root, f)}`);
    continue;
  }
  const w = b.readUInt32BE(16);
  const h = b.readUInt32BE(20);
  const colorType = b.readUInt8(25);
  const key = relative(join(root, "assets"), f);
  const exp = EXPECT[key];
  if (exp && (exp[0] !== w || exp[1] !== h))
    problems.push(`Wrong size ${key}: ${w}×${h}, expected ${exp.join("×")}`);
  if (ALPHA_REQUIRED.includes(key) && colorType !== 6)
    problems.push(`Expected transparency (RGBA) in ${key}`);
  if (b.length < 200) problems.push(`Suspiciously small PNG (placeholder?): ${key}`);
  if (!key.includes("/test/"))
    pngRows.push(
      `| \`${relative(root, f)}\` | ${w}×${h} | ${colorType === 6 ? "RGBA" : "RGB"} | ${(b.length / 1024).toFixed(1)} KB |`,
    );
}

// --- links
const linkSources = [
  ...walk(join(root, "previews")).filter((f) => f.endsWith(".html")),
  ...readdirSync(root)
    .filter((f) => f.endsWith(".md"))
    .map((f) => join(root, f)),
  ...walk(join(root, "assets")).filter((f) => f.endsWith(".html")),
];
let links = 0;
for (const f of linkSources) {
  const text = readFileSync(f, "utf8");
  const refs = [
    ...text.matchAll(/(?:src|href)="([^"#?]+)"/g),
    ...text.matchAll(/\]\(([^)#\s]+)(?:#[^)]*)?\)/g),
    ...text.matchAll(/url\(([^)"']+)\)/g),
  ].map((m) => m[1]);
  for (const ref of refs) {
    if (/^(https?:|data:|mailto:|file:)/.test(ref) || ref.startsWith("${")) continue;
    links++;
    if (!existsSync(resolve(dirname(f), ref))) problems.push(`Broken link in ${relative(root, f)} → ${ref}`);
  }
}

const md = [
  "# Asset validation",
  "",
  `_Generated by \`node scripts/qa.mjs\`._`,
  "",
  `- SVG files checked: **${svgs.length}** (well-formed, viewBox, \`<title>\` on non-test files)`,
  `- PNG files checked: **${pngs.length}** (signature, dimensions vs spec, alpha where required, non-placeholder size)`,
  `- Local links checked: **${links}** across ${linkSources.length} HTML/Markdown files`,
  `- Problems: **${problems.length}**`,
  "",
  ...(problems.length ? ["## Problems", "", ...problems.map((p) => `- ${p}`), ""] : []),
  "## Rendered rasters",
  "",
  "| File | Size | Channels | Bytes |",
  "|---|---|---|---|",
  ...pngRows,
  "",
];
writeFileSync(join(root, "qa/asset-validation.md"), md.join("\n"));
console.log(`SVG ${svgs.length} · PNG ${pngs.length} · links ${links} · problems ${problems.length}`);
for (const p of problems) console.log("  " + p);
process.exit(problems.length ? 1 : 0);
