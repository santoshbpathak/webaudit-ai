/**
 * Copies drizzle-kit SQL migrations into a TypeScript module so the migrator works
 * identically under tsx, Next.js bundles and Docker (no runtime file-path lookups).
 * Run after `pnpm --filter @webaudit/db generate`.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "migrations");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((f) => {
  const sql = readFileSync(join(dir, f), "utf8");
  return `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(sql)} },`;
});

writeFileSync(
  join(root, "src", "migrations.generated.ts"),
  `// AUTO-GENERATED by scripts/embed-migrations.ts — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${entries.join("\n")}\n];\n`,
);
console.log(`Embedded ${files.length} migration(s).`);
